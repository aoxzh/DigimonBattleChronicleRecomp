# ---------------------------------------------------------------------------
class Block:
    __slots__ = ("addr", "lines", "conf", "term", "ninsn")

    def __init__(self, addr, conf):
        self.addr = addr
        self.lines = []
        self.conf = conf
        self.term = None
        self.ninsn = 0


def disasm(i):
    """Compact comment text (approximate — comments only)."""
    n = i.name
    parts = [n]
    g = lambda v: ("f%d" % v if (n[:1] in ("ps",) or n[0] == "f") and
                   n not in ("frsp",) and v is not None else
                   ("r%d" % v if v is not None else None))
    seq = []
    if i.d is not None and n not in ("cmp", "cmpl", "cmpi", "cmpli", "tw",
                                     "twi", "bc", "mtcrf", "mfspr", "mtspr",
                                     "mftb", "mtfsb0", "mtfsb1", "mtfsfi",
                                     "mcrfs", "mtfsf", "mffs", "bclr",
                                     "bcctr"):
        seq.append(("f%d" if (n.startswith("f") or n.startswith("ps") or
                              n.startswith("stf") or n.startswith("lf") or
                              n.startswith("psq_l")) else "r%d") % i.d
                   if not n.startswith("st") else
                   ("f%d" if n.startswith("stf") or n.startswith("psq_st")
                    else "r%d") % i.d)
    for f in (i.a, i.b, i.c):
        if f is not None and n not in ("bc",):
            seq.append("r%d" % f)
    if i.simm is not None and n in ("addi", "addis", "addic", "subfic",
                                    "mulli", "cmpi", "cmpli", "ori", "oris",
                                    "xori", "xoris", "andi", "andis", "twi"):
        seq.append("%d" % i.simm)
    if seq:
        parts.append(", ".join(str(s) for s in seq))
    return " ".join(parts)


class Lifter:
    MAX_BLOCK_INSNS = 65536

    def __init__(self, text_secs, data_secs, entry, probe_blocks=()):
        self.text_secs = sorted(text_secs)
        self.probe_blocks = set(probe_blocks)
        self.data_secs = sorted(data_secs)
        self.entry = entry
        self.words = {}
        for base, blob in self.text_secs:
            for off in range(0, len(blob) - 3, 4):
                self.words[base + off] = int.from_bytes(blob[off:off + 4],
                                                        "big")
        self.text_ranges = [(b, b + len(blob)) for b, blob in self.text_secs]
        self.blocks = {}
        self.failed = {}          # addr -> (reason, conf)
        self.todo = deque()
        self.hist = Counter()
        self.func_starts = set([entry])
        self.n = 0
        self.unknown = []
        self.data_skipped = 0
        self.out = None
        self.cur_block = None

    # ------------------------------------------------------------------ util
    def in_text(self, addr):
        return any(lo <= addr < hi for lo, hi in self.text_ranges)

    def word_at(self, addr):
        return self.words.get(addr)

    @staticmethod
    def blkname(addr):
        return "b_%08x" % addr

    def L(self, tag):
        self.n += 1
        return "l%d_%s" % (self.n, tag)

    def rq(self, x):
        return "gc.r[%d]" % x

    def fq(self, x):
        return "gc.fpr_bits[%d]" % x

    def ea_d(self, i):
        if i.a == 0:
            return hx(i.simm or 0)
        return "(uint32_t)(%s + %s)" % (self.rq(i.a), hx(i.simm or 0))

    def ea_x(self, i):
        if i.a == 0:
            return self.rq(i.b)
        return "(uint32_t)(%s + %s)" % (self.rq(i.a), self.rq(i.b))

    def phys(self, ea):
        return "g_phys(%s)" % ea

    # --------------------------------------------------------------- lifting
    def run(self):
        self.todo.append((self.entry, True))
        self._drain()
        # data-segment pointer scan (function pointers / vtables): singles
        for base, blob in self.data_secs:
            for off in range(0, len(blob) - 3, 4):
                v = int.from_bytes(blob[off:off + 4], "big")
                if v & 3 or not self.in_text(v) or v in self.blocks:
                    continue
                self.todo.append((v, False))
        # .text jump-table scan: runs of >= 2 consecutive text pointers
        for base, blob in self.text_secs:
            run = []
            for off in range(0, len(blob) - 3, 4):
                v = int.from_bytes(blob[off:off + 4], "big")
                if v & 3 or not self.in_text(v):
                    if len(run) >= 2:
                        for t in run:
                            if t not in self.blocks:
                                self.todo.append((t, False))
                    run = []
                    continue
                run.append(v)
            if len(run) >= 2:
                for t in run:
                    if t not in self.blocks:
                        self.todo.append((t, False))
        # extra roots last: entry 遍历与数据扫描种子优先声明块边界，
        # 运行时回填/批量根只补缺口（避免伪函数起点吞掉已验证的块）。
        for rs in getattr(self, "extra_roots", []):
            if rs & 3 or rs not in self.blocks:
                self.todo.append((rs, True))
        self._drain()

    def _drain(self):
        while self.todo:
            addr, conf = self.todo.popleft()
            if addr & 3 or addr in self.blocks:
                continue
            prev = self.failed.get(addr)
            if prev is not None and not (conf and not prev[1]):
                continue          # already failed; only pseudo->conf retries
            self.lift_block(addr, conf)

    def lift_block(self, addr, conf):
        blk = Block(addr, conf)
        self.cur_block = blk
        self.out = blk.lines
        self.n = 0
        pc = addr
        succs = []
        while True:
            w = self.word_at(pc)
            if w is None:
                self._fail(addr, conf, pc, 0, "ran off text section")
                return False
            if w == 0:
                # inter-function padding word reached by traversal: stop as
                # data; only traps if actually executed at runtime
                blk.term = ("data", 0)
                self.out.append("    return gc_unimplemented(\"padding@%08x\", 0x%08x);"
                                % (addr, addr))
                self.blocks[addr] = blk
                self.data_skipped += 1
                return True
            i = dec_insn(w, pc)
            if i is None:
                self._fail(addr, conf, pc, w, "undecodable")
                return False
            blk.ninsn += 1
            self.hist[i.name] += 1
            term = self.emit(i, pc)
            if term is not None:
                kind = term[0]
                if kind == "b":
                    blk.term = ("b", term[1])
                    succs.append((term[1], conf))
                elif kind == "bl":
                    blk.term = ("bl", term[1], term[2])
                    succs.append((term[1], conf))
                    succs.append((term[2], conf))
                    self.func_starts.add(term[1])
                elif kind == "bc":
                    tgt, nxt, cond = term[1], term[2], term[3]
                    blk.term = ("bc", tgt, nxt, cond)
                    succs.append((tgt, conf))
                    if cond is not None:       # statically-always: no fall arm
                        succs.append((nxt, conf))
                elif kind == "ind":
                    blk.term = ("ind", term[1], term[2], term[3])
                    if term[2]:            # LK=1: 间接调用，pc+4 续块必可达
                        succs.append((pc + 4, conf))
                elif kind == "bcind":
                    blk.term = ("bcind", term[1], term[2], term[3],
                                term[4], term[5])
                    if term[2] or term[4] is not None:
                        succs.append((term[5], conf))
                elif kind == "rfi":
                    blk.term = ("rfi",)
                elif kind == "sc":
                    blk.term = ("sc", pc)
                self.blocks[addr] = blk
                for s in succs:
                    if s[0] not in self.blocks and self.in_text(s[0]):
                        self.todo.append(s)
                return True
            if blk.ninsn > self.MAX_BLOCK_INSNS:
                self._fail(addr, conf, pc, w, "block too long")
                return False
            pc += 4

    def _fail(self, addr, conf, pc, w, why):
        if conf:
            self.unknown.append((pc, w, why))
            self.failed[addr] = (why, conf)
        else:
            self.data_skipped += 1
            self.failed[addr] = (why, conf)

    # ---------------------------------------------------------------- output
    def jump(self, tgt):
        """Direct transfer as a statement; clang -O2 turns this into a
        sibling (tail) call so block hops do not grow the C stack."""
        if tgt in self.blocks:
            return "%s(); return;" % self.blkname(tgt)
        return "gc_dispatch(%s); return;" % hx(tgt)

    def render_term(self, blk):
        t = blk.term
        k = t[0]
        if k == "b":
            return "%s" % self.jump(t[1])
        if k == "bl":
            return "gc.lr = %s;\n    %s" % (hx(t[2]), self.jump(t[1]))
        if k == "fall":
            return "%s" % self.jump(t[1])
        if k == "bc":
            cond, tgt, nxt = t[3], t[1], t[2]
            if cond is None:
                return "%s" % self.jump(tgt)
            # Exact original scheduler loop: load runnable bits, compare zero,
            # branch back. The helper is only on its taken (empty queue) arm;
            # every iteration still executes the real load and CR/r0 updates.
            idle_words = (0x800d9c38, 0x28000000, 0x4182fff8)
            idle = (blk.addr == 0x802c7ae4 and blk.ninsn == 3 and
                    tgt == blk.addr and nxt == blk.addr + 12 and
                    tuple(self.word_at(blk.addr + 4*j) for j in range(3)) == idle_words)
            taken = ("hal_scheduler_idle(); " if idle else "") + self.jump(tgt)
            return "if (%s) { %s }\n    %s" % (
                cond, taken, self.jump(nxt))
        if k == "ind":
            reg, lk, ret = t[1], t[2], t[3]
            v = self.L("t")
            s = "{ uint32_t %s = %s & 0xFFFFFFFCu;\n    " % (v, reg)
            if lk:
                s += "gc.lr = %s;\n    " % hx(ret)
            s += "gc_dispatch(%s); return; }" % v
            return s
        if k == "bcind":
            reg, lk, ret, cond, nxt = t[1], t[2], t[3], t[4], t[5]
            v = self.L("t")
            body = "{ uint32_t %s = %s & 0xFFFFFFFCu;\n    " % (v, reg)
            if lk:
                body += "gc.lr = %s;\n    " % hx(ret)
            body += "gc_dispatch(%s); return; }" % v
            if cond is None:
                return body
            return "if (%s) {\n    %s\n    }\n    %s" % (
                cond, body, self.jump(nxt))
        if k == "rfi":
            return ("gc_msr_note((uint32_t)(gc.srr0 & 0xFFFFFFFCu), gc.msr, "
                    "gc.srr1); gc.msr = gc.srr1;\n    gc_dispatch(gc.srr0 & "
                    "0xFFFFFFFCu); return;")
        if k == "sc":
            return 'gc_unimplemented("sc", %s); return;' % hx(t[1])
        return ""

