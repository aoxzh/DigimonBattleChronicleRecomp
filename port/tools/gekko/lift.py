    # ------------------------------------------------------------ emitters
    def emit(self, i, pc):
        n = i.name
        com = "/* %08x: %08x  %s */ " % (pc, i.word, disasm(i))
        h = getattr(self, "e_" + n, None)
        if h is None:
            if self.cur_block.conf:
                self.unknown.append((pc, i.word, "unlifted:" + n))
            self.out.append('    %sgc_unimplemented("%s", %s);'
                            % (com, n, hx(pc)))
            return ("ind", "0", False, pc)      # unreachable placeholder
        return h(i, pc, com)

    # --- terminators ---
    def e_b(self, i, pc, com):
        tgt = (i.simm & M32) if i.aa else (pc + i.simm) & M32
        if i.lk:
            return ("bl", tgt, (pc + 4) & M32)
        return ("b", tgt)

    def e_bc(self, i, pc, com):
        tgt = (i.simm & M32) if i.aa else (pc + i.simm) & M32
        nxt = (pc + 4) & M32
        bo = i.bo
        if i.lk:
            self.out.append("    %sgc.lr = %s;" % (com, hx(nxt)))
            com = "    "
        if not (bo & 0x04):
            self.out.append("    %sgc.ctr = gc.ctr - 1u;" % com)
        cond = None
        if not (bo & 0x10):
            bit = 31 - i.bi
            want = 1 if (bo & 0x08) else 0
            cond = "((gc.cr >> %d) & 1u) == %du" % (bit, want)
            if not (bo & 0x04):
                zc = "gc.ctr == 0u" if (bo & 0x02) else "gc.ctr != 0u"
                cond = cond + " && " + zc
        elif not (bo & 0x04):
            cond = "gc.ctr == 0u" if (bo & 0x02) else "gc.ctr != 0u"
        return ("bc", tgt, nxt, cond)

    def _cond_ind(self, i, reg, nxt, com):
        """bclr/bcctr：BO 编码与 e_bc 相同。BEQLR/BNELR 等**条件**返回此前被
        当成无条件 blr 发射（MW 编译器辅助函数大量使用，lshrdi3/ashldi3
        因此整体错误——OSReport 死循环根因）。cond=None 表示无条件。"""
        bo = i.bo
        if not (bo & 0x04):
            self.out.append("    %sgc.ctr = gc.ctr - 1u;" % com)
            com = "    "
        cond = None
        if not (bo & 0x10):
            bit = 31 - i.bi
            want = 1 if (bo & 0x08) else 0
            cond = "((gc.cr >> %d) & 1u) == %du" % (bit, want)
            if not (bo & 0x04):
                zc = "gc.ctr == 0u" if (bo & 0x02) else "gc.ctr != 0u"
                cond = cond + " && " + zc
        elif not (bo & 0x04):
            cond = "gc.ctr == 0u" if (bo & 0x02) else "gc.ctr != 0u"
        return ("bcind", reg, i.lk, nxt, cond, nxt)

    def e_bclr(self, i, pc, com):
        return self._cond_ind(i, "gc.lr", (pc + 4) & M32, com)

    def e_bcctr(self, i, pc, com):
        return self._cond_ind(i, "gc.ctr", (pc + 4) & M32, com)

    def e_rfi(self, i, pc, com):
        return ("rfi",)

    def e_sc(self, i, pc, com):
        # 零售 SDK：sc 跳 0x80000C00 向量（BS2 写 rfi 兜底），进→出净效果为零。
        # DCFlushRange/DCStoreRange 等缓存函数尾部都以 sc 结尾（SDK 约定）。
        self.out.append('    %s/* sc -> 0xC00 rfi stub: net no-op */' % com)
        return None

    def e_isync(self, i, pc, com):
        self.out.append('    %s__asm__ __volatile__("" ::: "memory");' % com)

