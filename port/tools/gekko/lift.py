    def e_mtfsf(self, i, pc, com):
        fm = i.crm
        src = self.L("s")
        parts = ["{ uint32_t %s = (uint32_t)%s;" % (src, self.fq(i.b))]
        for k in range(8):
            if fm & (0x80 >> k):
                parts.append(" gc.fpscr = (gc.fpscr & ~%s) | (%s & %s);"
                             % (hx(0xF << (28 - 4 * k)), src,
                                hx(0xF << (28 - 4 * k))))
        parts.append("}")
        self.out.append("    %s%s" % (com, "".join(parts)))

