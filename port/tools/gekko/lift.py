    # --- psq loads/stores ---
    def _psq_ea(self, i, indexed):
        return self.ea_x(i) if indexed else self.ea_d(i)

    def _psq_load_body(self, i, p):
        w = i.w
        v0, v1 = self.L("p0"), self.L("p1")
        L = ["float %s, %s;" % (v0, v1)]
        L.append("switch ((gc.gqr[%d] >> 16) & 7u) {" % i.gqr)
        L.append("case 4u: %s = (float)g_pread8(%s) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v0, p, i.gqr))
        L.append("case 5u: %s = (float)g_pread16(%s) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v0, p, i.gqr))
        L.append("case 6u: %s = (float)(int32_t)(int8_t)g_pread8(%s) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v0, p, i.gqr))
        L.append("case 7u: %s = (float)(int32_t)(int16_t)g_pread16(%s) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v0, p, i.gqr))
        L.append("default: %s = g_bf32(g_pread32(%s)); break;" % (v0, p))
        L.append("}")
        if w:
            L.append("%s = 1.0f;" % v1)
        else:
            L.append("switch ((gc.gqr[%d] >> 16) & 7u) {" % i.gqr)
            L.append("case 4u: %s = (float)g_pread8((%s + 1u) & 0xFFFFFFFFu) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v1, p, i.gqr))
            L.append("case 5u: %s = (float)g_pread16((%s + 2u) & 0xFFFFFFFFu) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v1, p, i.gqr))
            L.append("case 6u: %s = (float)(int32_t)(int8_t)g_pread8((%s + 1u) & 0xFFFFFFFFu) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v1, p, i.gqr))
            L.append("case 7u: %s = (float)(int32_t)(int16_t)g_pread16((%s + 2u) & 0xFFFFFFFFu) * g_gqr_ldscale((gc.gqr[%d] >> 24) & 0x3Fu); break;" % (v1, p, i.gqr))
            L.append("default: %s = g_bf32(g_pread32((%s + 4u) & 0xFFFFFFFFu)); break;" % (v1, p))
            L.append("}")
        L.append("g_ps_set(%d, %s, %s);" % (i.d, v0, v1))
        return L

    def _psq_store_body(self, i, p):
        w = i.w
        v0 = self.L("q0")

        def one(v, pp):
            return [
                "switch (gc.gqr[%d] & 7u) {" % i.gqr,
                "case 4u: g_pwrite8(%s, (uint8_t)g_qtz(%s, 0, 255)); break;" % (pp, v),
                "case 5u: g_pwrite16(%s, (uint16_t)g_qtz(%s, 0, 65535)); break;" % (pp, v),
                "case 6u: g_pwrite8(%s, (uint8_t)g_qtz(%s, -128, 127)); break;" % (pp, v),
                "case 7u: g_pwrite16(%s, (uint16_t)g_qtz(%s, -32768, 32767)); break;" % (pp, v),
                "default: g_pwrite32(%s, g_f32b(%s)); break;" % (pp, v),
                "}",
            ]
        L = ["float %s = g_ps0(%s) * g_gqr_stscale((gc.gqr[%d] >> 8) & 0x3Fu);"
             % (v0, i.d, i.gqr)]
        L += one(v0, p)
        if not w:
            v1 = self.L("q1")
            L.append("float %s = g_ps1(%s) * g_gqr_stscale((gc.gqr[%d] >> 8) "
                     "& 0x3Fu);" % (v1, i.d, i.gqr))
            L += one(v1, "(%s + g_gqr_stride(gc.gqr[%d]))" % (p, i.gqr))
        return L

    def _psq(self, i, pc, com, store, indexed, upd):
        p = self.L("p")
        body = (self._psq_store_body if store else self._psq_load_body)(i, p)
        o = self.out
        o.append("    %s{ uint32_t %s = g_phys(%s);"
                 % (com, p, self._psq_ea(i, indexed)))
        for ln in body:
            o.append("      " + ln)
        if upd:
            o.append("      gc.r[%d] = (uint32_t)(%s);" % (
                i.a, self._psq_ea(i, indexed)))
        o.append("    }")

