"""lift.py — PPC Gekko DOL -> C static lifter.

Lifts every reachable basic block of a GameCube DOL into continuation-style
C functions (void b_<addr8>(void)), plus the runtime support files:

    recomp/gen_prefix.h            static-inline semantic helpers
    recomp/generated/b_XXXXXXXX.c  block bodies (<=400 blocks per file)
    recomp/blocks.c                block table + gc_block_lookup + SPR shadows
    recomp/recomp_entry.c          gc_entry -> entry block

Continuation model: every block ends with `return b_next();` (tail call) or
`return gc_dispatch(target);` — compile with -O1+ so clang performs
tail-call elimination and the C stack stays flat.

IRQ injection: each block entry calls hal_irq_poll_cycles(0); a non-zero return
is the injected vector address and the block dispatches to it immediately.
Executed blocks commit their original instruction count before the terminator;
one nominal CPU cycle/instruction is approximate, not Gekko pipeline timing.

TBL/TBU (mftb / mfspr 268/269/284/285) read the HAL's shared CPU/12 clock.
DEC writes use the HAL hook to preserve its fractional phase and pending edge.
gc.icount counts original executed instructions, including branch terminators.
"""

