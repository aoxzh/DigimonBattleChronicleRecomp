    def e_mtcrf(self, i, pc, com):
        m = 0
        for k in range(8):
            if i.crm & (0x80 >> k):
                m |= 0xF << (28 - 4 * k)
        # r91 修复：模板的 `~` 与 hx(~m) 的预补码叠加成双重取反，掩码反相
        # （保留被写字段、清掉其余字段），CR0 残留位永久粘住——Lua 表 resize
        # 据此走错 dummynode 分支，开机 60 帧即卡死。hx 实参应为清除掩码本身。
        self.out.append("    %sgc.cr = (gc.cr & %s) | (%s & %s);"
                        % (com, hx(~m & M32), self.rq(i.d), hx(m)))

