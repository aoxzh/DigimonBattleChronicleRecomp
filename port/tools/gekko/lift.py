    def e_mulli(self, i, pc, com):
        self.out.append("    %s%s = (uint32_t)((int64_t)(int32_t)%s * (int64_t)(%d));"
                        % (com, self.rq(i.d), self.rq(i.a), i.simm))

    def _logic_imm(self, i, pc, com, op, shift):
        # D-form 逻辑：ori rA,rS,uimm — 目标=A 字段，源=D 字段(rS)
        a = "(%s %s %s)" % (self.rq(i.d), op, hx((i.uimm << shift) & M32))
        self.out.append("    %s%s = %s;%s" % (
            com, self.rq(i.a), a,
            " g_cr0(%s);" % self.rq(i.a) if i.rc else ""))

    def e_ori(self, i, pc, com):
        if i.d == 0 and i.a == 0 and i.uimm == 0:
            self.out.append("    %s/* nop */" % com)
            return
        self._logic_imm(i, pc, com, "|", 0)

    def e_oris(self, i, pc, com):   self._logic_imm(i, pc, com, "|", 16)
    def e_xori(self, i, pc, com):   self._logic_imm(i, pc, com, "^", 0)
    def e_xoris(self, i, pc, com):  self._logic_imm(i, pc, com, "^", 16)
    def e_andi(self, i, pc, com):   self._logic_imm(i, pc, com, "&", 0)
    def e_andis(self, i, pc, com):  self._logic_imm(i, pc, com, "&", 16)

    # --- compares ---
    def _cmp(self, i, pc, com, a_e, b_e, signed):
        r = self.L("f")
        if signed:
            body = ("if ((int32_t)%s < (int32_t)%s) %s = 8u; "
                    "else if ((int32_t)%s > (int32_t)%s) %s = 4u; "
                    "else %s = 2u;" % (a_e, b_e, r, a_e, b_e, r, r))
        else:
            body = ("if (%s < %s) %s = 8u; else if (%s > %s) %s = 4u; "
                    "else %s = 2u;" % (a_e, b_e, r, a_e, b_e, r, r))
        self.out.append("    %s{ uint32_t %s; %s %s |= (gc.xer >> 31) & 1u; "
                        "g_crf(%d, %s); }"
                        % (com, r, body, r, i.crfd, r))

    def e_cmpi(self, i, pc, com):
        self._cmp(i, pc, com, self.rq(i.a), hx(i.simm & M32), True)

    def e_cmpli(self, i, pc, com):
        self._cmp(i, pc, com, self.rq(i.a), hx(i.uimm), False)

    def e_cmp(self, i, pc, com):
        self._cmp(i, pc, com, self.rq(i.a), self.rq(i.b), True)

    def e_cmpl(self, i, pc, com):
        self._cmp(i, pc, com, self.rq(i.a), self.rq(i.b), False)

    # --- traps ---
    def _trap(self, to, a_e, b_e, pc, com):
        parts = []
        if to & 0x10:
            parts.append("(int32_t)%s < (int32_t)%s" % (a_e, b_e))
        if to & 0x08:
            parts.append("(int32_t)%s > (int32_t)%s" % (a_e, b_e))
        if to & 0x04:
            parts.append("%s == %s" % (a_e, b_e))
        if to & 0x02:
            parts.append("%s < %s" % (a_e, b_e))
        if to & 0x01:
            parts.append("%s > %s" % (a_e, b_e))
        if not parts:
            return
        self.out.append("    %s{ if (%s) { gc_trap(%s); return; } }"
                        % (com, " || ".join(parts), hx(pc)))

    def e_twi(self, i, pc, com):
        self._trap(i.d, self.rq(i.a), hx(i.simm & M32), pc, com)

    def e_tw(self, i, pc, com):
        self._trap(i.to, self.rq(i.a), self.rq(i.b), pc, com)

