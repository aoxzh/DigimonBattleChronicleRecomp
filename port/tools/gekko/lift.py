        s = ("    %s{ uint32_t %s, %s; %s = (uint32_t)((uint64_t)%s + "
             "(uint64_t)%s + (uint64_t)(%s)); " % (
                 com, r, ca, r, x, y, cin_e))
        if set_ca:
            s += "%s = g_ca3(%s, %s, %s); " % (ca, x, y, cin_e)
        if i.oe and ov_x is not None:
            s += " g_set_ov(g_ov_add(%s, %s, %s));" % (ov_x, ov_y, r)
        s += "%s = %s;" % (self.rq(i.d), r)
        if set_ca:
            s += " g_set_ca(%s);" % ca
        if i.rc:
            s += " g_cr0(%s);" % self.rq(i.d)
        self.out.append(s + " }")

